using System.Collections.Generic;
using System.ComponentModel.DataAnnotations;
using System.Text.Json.Serialization;
using Square.Core.Models;
using Square.Models.Enums;

namespace Square.Models;

/// <summary>
/// Contains details about how to fulfill this order.
/// Orders can only be created with at most one fulfillment using the API.
/// However, orders returned by the Orders API might contain multiple fulfillments because sellers can create multiple fulfillments using Square products such as Square Online.
/// </summary>
public record Fulfillment
{
    /// <summary>
    /// A unique ID that identifies the fulfillment only within this order.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("uid")]
    [MaxLength(60)]
    public string? Uid { get; init; }

    /// <summary>
    /// The type of fulfillment.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("type")]
    public FulfillmentType? Type { get; init; }

    /// <summary>
    /// The current state of this fulfillment.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("state")]
    public FulfillmentState? State { get; init; }

    /// <summary>
    /// The <c>line_item_application</c> describes what order line items this fulfillment applies
    /// to. It can be <c>ALL</c> or <c>ENTRY_LIST</c> with a supplied list of fulfillment entries.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("line_item_application")]
    public FulfillmentFulfillmentLineItemApplication? LineItemApplication { get; init; }

    /// <summary>
    /// A list of entries pertaining to the fulfillment of an order. Each entry must reference
    /// a valid <c>uid</c> for an order line item in the <c>line_item_uid</c> field, as well as a <c>quantity</c> to
    /// fulfill.
    /// <para>
    /// Multiple entries can reference the same line item <c>uid</c>, as long as the total quantity among
    /// all fulfillment entries referencing a single line item does not exceed the quantity of the
    /// order's line item itself.
    /// </para>
    /// <para>
    /// An order cannot be marked as <c>COMPLETED</c> before all fulfillments are <c>COMPLETED</c>,
    /// <c>CANCELED</c>, or <c>FAILED</c>. Fulfillments can be created and completed independently
    /// before order completion.
    /// </para>
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("entries")]
    public IReadOnlyList<FulfillmentFulfillmentEntry>? Entries { get; init; }

    /// <summary>
    /// Application-defined data attached to this fulfillment. Metadata fields are intended
    /// to store descriptive references or associations with an entity in another system or store brief
    /// information about the object. Square does not process this field; it only stores and returns it
    /// in relevant API calls. Do not use metadata to store any sensitive information (such as personally
    /// identifiable information or card details).
    /// <para>
    /// Keys written by applications must be 60 characters or less and must be in the character set
    /// <c>[a-zA-Z0-9_-]</c>. Entries can also include metadata generated by Square. These keys are prefixed
    /// with a namespace, separated from the key with a ':' character.
    /// </para>
    /// <para>
    /// Values have a maximum length of 255 characters.
    /// </para>
    /// <para>
    /// An application can have up to 10 entries per metadata field.
    /// </para>
    /// <para>
    /// Entries written by applications are private and can only be read or modified by the same
    /// application.
    /// </para>
    /// <para>
    /// For more information, see <see href="https://developer.squareup.com/docs/build-basics/metadata">Metadata</see>.
    /// </para>
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("metadata")]
    public IReadOnlyDictionary<string, string?>? Metadata { get; init; }

    /// <summary>
    /// Contains details necessary to fulfill a pickup order.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("pickup_details")]
    public FulfillmentPickupDetails? PickupDetails { get; init; }

    /// <summary>
    /// Contains the details necessary to fulfill a shipment order.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("shipment_details")]
    public FulfillmentShipmentDetails? ShipmentDetails { get; init; }

    /// <summary>
    /// Describes delivery details of an order fulfillment.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("delivery_details")]
    public FulfillmentDeliveryDetails? DeliveryDetails { get; init; }

    /// <summary>
    /// Contains the details necessary to fulfill an in-store order.
    /// </summary>
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    [JsonPropertyName("in_store_details")]
    public FulfillmentInStoreDetails? InStoreDetails { get; init; }

    [JsonExtensionData]
    public AdditionalProperties AdditionalProperties { get; init; } = [];
}
